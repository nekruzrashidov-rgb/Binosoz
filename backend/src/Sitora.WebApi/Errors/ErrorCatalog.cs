// Каталог текстов ошибок API: русский текст (как его бросает сервис или валидатор) → стабильный машиночитаемый code
// и таджикский перевод. Сервисы пишут ошибки по-русски, как раньше; ответ получает code и, при Accept-Language: tg,
// таджикский текст. Текст, которого здесь нет (с подставленными значениями, редкий), остаётся русским, а code берётся
// по типу исключения (not_found, conflict, business_rule…).
// Таджикские формулировки — литературный таджикский, кириллица; перед запуском их должен вычитать носитель языка.
public static class ErrorCatalog
{
    public record Entry(string Code, string Tg);

    private static readonly Dictionary<string, Entry> Exact = new(StringComparer.Ordinal);
    // Тексты с подставленным хвостом («Неизвестная роль: X»): совпадение по началу, хвост переносится как есть.
    private static readonly List<(string Prefix, Entry Entry)> Prefixes = [];

    private static void E(string ru, string code, string tg) => Exact[ru] = new Entry(code, tg);
    private static void P(string ruPrefix, string code, string tgPrefix) => Prefixes.Add((ruPrefix, new Entry(code, tgPrefix)));

    public static bool TryFind(string? ru, out Entry entry, out string tgText)
    {
        entry = null!;
        tgText = string.Empty;
        if (string.IsNullOrEmpty(ru))
            return false;
        if (Exact.TryGetValue(ru, out var found))
        {
            entry = found;
            tgText = found.Tg;
            return true;
        }
        foreach (var (prefix, e) in Prefixes)
        {
            if (ru.StartsWith(prefix, StringComparison.Ordinal))
            {
                entry = e;
                tgText = e.Tg + ru[prefix.Length..];
                return true;
            }
        }
        return false;
    }

    public static string Translate(string ru, bool tajik) => tajik && TryFind(ru, out _, out var tg) ? tg : ru;

